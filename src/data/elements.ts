export function getElementBySymbol(symbol: string): ChemicalElement | undefined {
  return ELEMENTS_DATA.find(e => e.symbol.toLowerCase() === symbol.toLowerCase());
}

export function getElementByNumber(atomicNumber: number): ChemicalElement | undefined {
  return ELEMENTS_DATA.find(e => e.atomicNumber === atomicNumber);
}

// Berechnet die Elektronenkonfiguration nach dem Bohrschen Schalenmodell (K, L, M, N, O, P, Q)
export function getElectronShells(atomicNumber: number): number[] {
  const exactShells: Record<number, number[]> = {
    1: [1],
    2: [2],
    3: [2, 1],
    4: [2, 2],
    5: [2, 3],
    6: [2, 4],
    7: [2, 5],
    8: [2, 6],
    9: [2, 7],
    10: [2, 8],
    11: [2, 8, 1],
    12: [2, 8, 2],
    13: [2, 8, 3],
    14: [2, 8, 4],
    15: [2, 8, 5],
    16: [2, 8, 6],
    17: [2, 8, 7],
    18: [2, 8, 8],
    19: [2, 8, 8, 1],
    20: [2, 8, 8, 2],
    22: [2, 8, 10, 2],
    24: [2, 8, 13, 1],
    26: [2, 8, 14, 2],
    28: [2, 8, 16, 2],
    29: [2, 8, 18, 1],
    30: [2, 8, 18, 2],
    35: [2, 8, 18, 7],
    36: [2, 8, 18, 8],
    47: [2, 8, 18, 18, 1],
    50: [2, 8, 18, 18, 4],
    53: [2, 8, 18, 18, 7],
    54: [2, 8, 18, 18, 8],
    56: [2, 8, 18, 18, 8, 2],
    78: [2, 8, 18, 32, 17, 1],
    79: [2, 8, 18, 32, 18, 1],
    80: [2, 8, 18, 32, 18, 2],
    82: [2, 8, 18, 32, 18, 4],
    92: [2, 8, 18, 32, 21, 9, 2]
  };

  if (exactShells[atomicNumber]) {
    return exactShells[atomicNumber];
  }

  // Fallback: Näherung nach maximaler Schalenbesetzung 2n^2
  const maxCap = [2, 8, 18, 32, 32, 18, 8];
  let rem = atomicNumber;
  const res: number[] = [];
  for (const cap of maxCap) {
    if (rem <= 0) break;
    const count = Math.min(rem, cap);
    res.push(count);
    rem -= count;
  }
  return res;
}
